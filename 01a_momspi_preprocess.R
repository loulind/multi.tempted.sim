# ============================================================================
# 01a_momspi_preprocess.R
#
# PURPOSE
# Build the analysis-ready MOMS-PI data used by 01_momspi.R and
# supp_momspi_stability.R: vaginal 16S microbiome counts and cervicovaginal
# cytokines from the first six visits, for women with spontaneous preterm
# birth (PTB) or term birth (TB) and at least two samples in each assay.
#
# INPUTS (data/momspi/, not tracked; see the Data section of README.md for sources)
#   momspi16S_samp.rda, momspi16S_mtx.rda, momspi16S_tax.rda   16S metadata,
#       OTU counts (taxa x samples) and taxonomy, from HMP2Data
#   momspiCyto_samp.rda, momspiCyto_mtx.rda                     cytokine
#       metadata and concentrations (cytokines x samples), from HMP2Data
#   Vaginal_microbiome_log_ratios_per_sample_Pixu.csv           pregnancy
#       outcome (PTB / TB) per subject, from the TEMPTED paper repository
#
# STEPS
#   1. keep vaginal samples at visits 1-6 from subjects with a known outcome
#   2. keep subjects with >= 2 samples in BOTH assays
#   3. microbiome: drop taxa present in <= 5% of samples (pooled into "Other"),
#      replace zeros by a pseudocount of 0.5, CLR-transform
#   4. cytokines: drop cytokines detected in < 10% of samples, replace
#      non-positive values by half the smallest positive value of that
#      cytokine, log2-transform
#
# OUTPUT
#   data/momspi/processed/*.csv (regenerated by this script; not tracked by git)
# ============================================================================

# Everything is read from and written to folders beside this script, NOT
# getwd(), so it runs the same from source()/RStudio "Source" or Rscript.
.scriptdir <- local({
  d <- NULL
  for (i in seq_len(sys.nframe())) {                    # source() / RStudio Source
    of <- sys.frame(i)$ofile
    if (!is.null(of)) { d <- dirname(normalizePath(of, mustWork = FALSE)); break }
  }
  if (is.null(d)) {                                     # Rscript 01a_momspi_preprocess.R
    a <- commandArgs(trailingOnly = FALSE)
    a <- sub("^--file=", "", a[grepl("^--file=", a)])
    if (length(a)) d <- dirname(normalizePath(a[1], mustWork = FALSE))
  }
  if (is.null(d) && requireNamespace("rstudioapi", quietly = TRUE) &&
      rstudioapi::isAvailable()) {                      # RStudio, running lines by hand
    p <- tryCatch(rstudioapi::getSourceEditorContext()$path, error = function(e) NULL)
    if (!is.null(p) && nzchar(p)) d <- dirname(normalizePath(p, mustWork = FALSE))
  }
  if (is.null(d)) {
    d <- getwd()
    warning("could not locate the script file; using ", d, call. = FALSE)
  }
  d
})
.indir  <- file.path(.scriptdir, "data", "momspi")
.outdir <- file.path(.indir, "processed")
.need <- c(paste0(c("momspi16S_samp", "momspi16S_mtx", "momspi16S_tax", "momspiCyto_mtx",
                    "momspiCyto_samp"), ".rda"), "Vaginal_microbiome_log_ratios_per_sample_Pixu.csv")
.missing <- .need[!file.exists(file.path(.indir, .need))]
if (length(.missing))
  stop("place the MOMS-PI input files listed in README.md (Data section) in ", .indir,
       "\n  missing: ", paste(.missing, collapse = ", "), call. = FALSE)
dir.create(.outdir, showWarnings = FALSE, recursive = TRUE)
cat(sprintf("input directory : %s\noutput directory: %s\n", .indir, .outdir))


# ============================================================================
# load inputs
# ============================================================================
# .rda objects and what they contain
#   momspi16S_samp  : data.frame  9107 samples x 13 metadata columns
#   momspi16S_mtx   : matrix      7665 taxa    x 9107 samples (OTU counts)
#   momspi16S_tax   : matrix      7665 taxa    x 7 taxonomy ranks
#   momspiCyto_samp : data.frame  1396 samples x 13 metadata columns
#   momspiCyto_mtx  : matrix        29 cytokines x 1396 samples
for (f in c("momspi16S_samp", "momspi16S_mtx", "momspi16S_tax",
            "momspiCyto_mtx", "momspiCyto_samp"))
  load(file.path(.indir, paste0(f, ".rda")))

# The subject_id column of these objects holds hashed identifiers, while the
# row names carry the original "EP..." sample IDs used by the outcome file, so
# the subject is taken as the token before the first underscore.
momspi16S_samp$subject_ep  <- sub("_.*", "", rownames(momspi16S_samp))
momspiCyto_samp$subject_ep <- sub("_.*", "", rownames(momspiCyto_samp))

# Pregnancy outcome: column 'subjects' = EP-style subject ID, 'Group' = PTB/TB
outcome_raw <- utils::read.csv(file.path(.indir, "Vaginal_microbiome_log_ratios_per_sample_Pixu.csv"),
                               row.names = 1, stringsAsFactors = FALSE)
outcome_df  <- outcome_raw[!duplicated(outcome_raw$subjects), c("subjects", "Group")]
cat("subjects with known outcome:", nrow(outcome_df), "\n")


# ============================================================================
# 1-2. sample and subject filtering
# ============================================================================
samp_vagina <- momspi16S_samp[momspi16S_samp$sample_body_site == "vagina" &
                                momspi16S_samp$visit_number <= 6, ]
samp_cyto_vagina <- momspiCyto_samp[momspiCyto_samp$sample_body_site == "vagina" &
                                      momspiCyto_samp$visit_number <= 6, ]
known_subjects   <- outcome_df$subjects
samp_vagina      <- samp_vagina[samp_vagina$subject_ep %in% known_subjects, ]
samp_cyto_vagina <- samp_cyto_vagina[samp_cyto_vagina$subject_ep %in% known_subjects, ]

num_vagina   <- table(samp_vagina$subject_ep)
num_cytokine <- table(samp_cyto_vagina$subject_ep)
vec_subID    <- intersect(names(num_vagina), names(num_cytokine))
vec_subID    <- vec_subID[num_vagina[vec_subID] >= 2 & num_cytokine[vec_subID] >= 2]
cat("subjects retained:", length(vec_subID), "\n")

samp_vagina      <- samp_vagina[samp_vagina$subject_ep %in% vec_subID, ]
samp_cyto_vagina <- samp_cyto_vagina[samp_cyto_vagina$subject_ep %in% vec_subID, ]
count_16s    <- t(momspi16S_mtx[, rownames(samp_vagina)])         # samples x taxa
mtx_cytokine <- t(momspiCyto_mtx[, rownames(samp_cyto_vagina)])   # samples x cytokines

# attach the outcome to the sample metadata, keeping the original row order
.add_outcome <- function(meta, samp) {
  meta <- merge(meta, outcome_df, by.x = "subject_ep", by.y = "subjects", all.x = TRUE)
  rownames(meta) <- meta$sample_id
  meta <- meta[samp$sample_id, ]
  rownames(meta) <- rownames(samp)
  meta[, colnames(meta) != "urls"]
}
meta_16s      <- .add_outcome(data.frame(samp_vagina,      stringsAsFactors = FALSE), samp_vagina)
meta_cytokine <- .add_outcome(data.frame(samp_cyto_vagina, stringsAsFactors = FALSE), samp_cyto_vagina)
grp <- unique(meta_16s[, c("subject_ep", "Group")])
cat(sprintf("PTB: %d subjects, TB: %d subjects; %d microbiome and %d cytokine samples\n",
            sum(grp$Group == "PTB"), sum(grp$Group == "TB"), nrow(count_16s), nrow(mtx_cytokine)))


# ============================================================================
# 3. microbiome: rare-taxon filter, pseudocount, CLR
# ============================================================================
sel <- colMeans(count_16s == 0) <= 0.95
cat("taxa retained:", sum(sel), "of", length(sel), "\n")
count_16s_filter <- cbind(count_16s[, sel, drop = FALSE],
                          Other = rowSums(count_16s[, !sel, drop = FALSE]))
prop_16s <- count_16s_filter
prop_16s[prop_16s == 0] <- 0.5                         # pseudocount
prop_16s <- prop_16s / rowSums(prop_16s)
clr_16s  <- log(prop_16s)
clr_16s  <- clr_16s - rowMeans(clr_16s)


# ============================================================================
# 4. cytokines: detection filter, half-minimum imputation, log2
# ============================================================================
# Non-positive values are below-detection sentinels (-2, -1) or zeros.
frac_detected <- colMeans(mtx_cytokine > 0)
keep_cyto     <- frac_detected >= 0.10
cat("cytokines dropped (detected in < 10% of samples):",
    paste(names(frac_detected)[!keep_cyto], collapse = ", "), "\n")
mtx_cyto_log2 <- mtx_cytokine[, keep_cyto, drop = FALSE]
for (cyt in colnames(mtx_cyto_log2)) {
  lod_half <- min(mtx_cyto_log2[mtx_cyto_log2[, cyt] > 0, cyt]) / 2
  mtx_cyto_log2[mtx_cyto_log2[, cyt] <= 0, cyt] <- lod_half
}
mtx_cyto_log2 <- log2(mtx_cyto_log2)
cat("cytokines retained:", ncol(mtx_cyto_log2), "\n")


# ============================================================================
# write
# ============================================================================
.w <- function(x, f) utils::write.csv(x, file.path(.outdir, f))
.w(meta_16s,         "MOMSPI_microbiome_meta.csv")
.w(count_16s,        "MOMSPI_microbiome_count.csv")
.w(count_16s_filter, "MOMSPI_microbiome_count_filter.csv")
.w(clr_16s,          "MOMSPI_microbiome_clr.csv")
.w(momspi16S_tax,    "MOMSPI_microbiome_taxa.csv")
.w(meta_cytokine,    "MOMSPI_cytokine_meta.csv")
.w(mtx_cytokine,     "MOMSPI_cytokine_mtx.csv")
.w(mtx_cyto_log2,    "MOMSPI_cytokine_log2.csv")
cat(sprintf("processed data written to %s\n", normalizePath(.outdir, mustWork = FALSE)))
